#: 出图依赖的源文件（改了其中任何一个，图都该重画一次）。
#: 与内容模块同目录（都在 ``app/``），所以这里只写文件名。
SOURCE_FILES = ("helpcard_content.py", "helpcard.py")


#: 图里**不能出现**的 Markdown 记号：渲染器只会画字，星号会原样印出来
_MARKDOWN_MARKERS = ("**", "`", "__")


def _all_texts() -> Iterator[str]:
    """内容里**所有**会画到图上的字符串（供下面的检查用）。"""
    yield from (SUBTITLE, TITLE, TITLE_LABEL, PRIVACY_TITLE)
    for label, text in PRIVACY:
        yield label
        yield text
    for section_title, rows in SECTIONS:
        yield section_title
        yield SECTION_NOTES.get(section_title, "")
        for cmd, desc in rows:
            yield cmd
            yield desc


def markdown_leaks() -> list[str]:
    """文案里混进 Markdown 记号的地方（图只会画字，符号会原样印出来）。"""
    return [text for text in _all_texts() if text and any(m in text for m in _MARKDOWN_MARKERS)]


def source_digest() -> str:
    """出图源文件的指纹（``SOURCE_FILES`` 内容拼起来算 sha256）。

    图不入库，但本地可能有一份（服务启动时生成的）。自检与测试拿它比对
    「这份图是不是比文案旧」——图上的命令群友会照着打，错了就是毫无反应。
    """
    here = Path(__file__).resolve().parent
    hasher = hashlib.sha256()
    for name in SOURCE_FILES:
        path = here / name
        hasher.update(name.encode("utf-8"))
        hasher.update(b"\0")
        hasher.update(path.read_bytes() if path.is_file() else b"")
        hasher.update(b"\0")
    return hasher.hexdigest()
